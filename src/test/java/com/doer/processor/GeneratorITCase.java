    /**
     * Keep the anonymous subclass of _GeneratedDoerService assigned to var: no other test has it. Main.java refers to
     * the class that DoerProcessor generates in the same javac run, calls its protected _load/_save, and through var
     * calls tst_load() and tst_save(), which only the anonymous class declares. Other tests use the named
     * TestDoerService instead.
     *
     * <p>_load of a type without @TaskDataLoader throws IllegalArgumentException; _save of a type without
     * @TaskDataSaver does nothing.
     */
    @Test
    void task_data__should_be_loaded_and_saved_by_type() throws Exception {
        writeSource("Main.java", """
                package demo.test;
                import com.doer.*;
                import com.doer.generated._GeneratedDoerService;
                public class Main {
                    public static void main(String[] args) throws Exception {
                        var doer = new _GeneratedDoerService() {
                            Object tst_load(Task task, Class<?> type) throws Exception {
                                return _load(task, type);
                            }
                            void tst_save(Task task, Class<?> type, Object data) throws Exception {
                                _save(task, type, data);
                            }
                        };
                        doer._inject_main(new Main());
                        Task task = new Task();
                        task.setStatus("A");

                        Object data = doer.tst_load(task, String.class);
                        System.out.println("---loaded-" + data + "---");
                        doer.tst_save(task, String.class, data);

                        try {
                            doer.tst_load(task, Integer.class);
                            System.out.println("---Integer-loaded---");
                        } catch (IllegalArgumentException e) {
                            System.out.println("---" + e.getMessage() + "---");
                        }
                        doer.tst_save(task, Integer.class, 42);
                        System.out.println("---Integer-save-ignored---");
                    }
                    @TaskDataLoader
                    public String loaderMethod(Task task) {
                        System.out.println("---load-String-for-" + task.getStatus() + "---");
                        return "d2";
                    }
                    @TaskDataSaver
                    public void saverMethod(Task task, String data) {
                        System.out.println("---save-String-" + data + "---");
                    }
                }
                """);
        javac("Main.java").assertStatus(0);

        var result = java("demo.test.Main").assertStatus(0);

        assertEquals("""
                ---load-String-for-A---
                ---loaded-d2---
                ---save-String-d2---
                ---No @TaskDataLoader for java.lang.Integer---
                ---Integer-save-ignored---
                """, result.stdOut());
    }

