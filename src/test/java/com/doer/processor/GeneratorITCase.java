    /**
     * The second javac run is the compilation of tests, as a build tool does it: the main classes, with
     * _GeneratedDoerService, are on the classpath, and the processor is on the processor path again. The processor
     * must see that and generate nothing (DoerProcessor.isCompilingTests).
     */
    @Test
    void processor_should_not_generate_when_compiling_tests() throws Exception {
        writeSource("Doer1.java", """
                package demo.test;
                import com.doer.*;
                public class Doer1 {
                    @AcceptStatus("A")
                    public void method1(Task task) {}
                }
                """);
        writeSource("DoerMethodInTests.java", """
                package demo.test;
                import com.doer.*;
                public class DoerMethodInTests {
                    @AcceptStatus("Test sources are compiled")
                    public void doerMethod(Task task) {}
                }
                """);
        javac("Doer1.java").assertStatus(0);
        String mainService = generatedService();

        var result = Toolchain.javac(workspace, "javac-tests", Toolchain.runClasspath("classes"), "test-classes",
                "DoerMethodInTests.java").assertStatus(0);

        assertTrue(Files.isRegularFile(workspace.resolve("test-classes/demo/test/DoerMethodInTests.class")));
        assertThat(result.stdErr(),
                containsString("The class _GeneratedDoerService is already present in dependencies"));
        assertFalse(Files.exists(workspace.resolve("test-classes/com/doer/generated")));
        assertEquals(mainService, generatedService());
    }
